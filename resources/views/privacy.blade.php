  <h1>Data Privacy Notice</h1>
  <div class="sub">Issued under the Philippine Data Privacy Act of 2012 (RA 10173) by the Terra Nova Homeowners Association (TNHOA) through the SubSync portal.</div>

  <h2>1. What we collect</h2>
  <ul>
    <li><strong>Account data:</strong> full name, email address, contact number, password (stored hashed), and profile photo (optional).</li>
    <li><strong>Household data:</strong> block and lot number and the list of household members you register.</li>
    <li><strong>Community submissions:</strong> issue reports (including photos/documents and map location you provide), suggestions, payment references and proof-of-payment screenshots, event RSVPs, and messages with the HOA office.</li>
    <li><strong>Usage records:</strong> activity and audit logs recording actions inside the portal (who did what and when).</li>
  </ul>

  <h2>2. Why we process it</h2>
  <ul>
    <li>To verify membership and manage HOA records, dues, and official receipts.</li>
    <li>To receive, route, and resolve community concerns and requests.</li>
    <li>To send announcements, reminders, and official communications.</li>
    <li>To keep an accountable audit trail of administrative actions, as required for HOA governance.</li>
  </ul>

  <h2>3. How it is stored and shared</h2>
  <p>Data is stored on the association's SubSync server. Issue photos, documents, officer files, and payment receipts are stored in private storage and are served only to authorized users (staff, or the resident concerned). We do not sell personal data. Access is limited to authorized HOA officers and administrators, and information is disclosed to third parties only when required by law.</p>

  <h2>4. Retention</h2>
  <p>Account and household records are kept while you are a member of the association. Activity logs are pruned periodically (currently after 180 days). Issue reports and their attachments are retained for HOA records and archive purposes after resolution.</p>

  <h2>5. Your rights</h2>
  <p>Under RA 10173 you have the right to be informed, to object, to access, to correct, and to erasure or blocking of your personal data, and to file a complaint with the National Privacy Commission (privacy.gov.ph).</p>
  <ul>
    <li><strong>Access / portability:</strong> download a copy of your personal data from <em>Settings → Privacy &amp; Data → Download my data</em>.</li>
    <li><strong>Correction:</strong> update your profile from Settings, or request corrections from the HOA office.</li>
    <li><strong>Erasure:</strong> submit a request from <em>Settings → Privacy &amp; Data → Request account erasure</em>. The HOA office will act on it within 15 working days, subject to legal retention requirements.</li>
  </ul>

  <h2>6. Contact</h2>
  <p>For privacy questions or requests, contact the TNHOA office at the numbers or email published in the HOA bulletin, or message the Administration through the SubSync Messages tab.</p>

  <div class="foot">By creating an account you confirm that you have read and accepted this notice. This notice may be updated; residents will be informed of material changes through official announcements.</div>
